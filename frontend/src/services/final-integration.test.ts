import { beforeEach, afterEach, expect, it, vi } from 'vitest'
let auth: typeof import('./authService')
let history: typeof import('./attemptHistoryService')
let attempts: typeof import('./attemptService')
const fetchMock = vi.fn()
const reply = (body: unknown, status = 200) => ({ ok: status >= 200 && status < 300, status, json: async () => body })
beforeEach(async () => {
  sessionStorage.clear(); vi.resetModules(); fetchMock.mockReset(); vi.stubGlobal('fetch', fetchMock)
  auth = await import('./authService'); history = await import('./attemptHistoryService'); attempts = await import('./attemptService')
  fetchMock.mockResolvedValueOnce(reply({ token: 'student-token', authenticatedUser: { id: 'student', name: 'Student', email: 'student@example.test', role: 'student' } }))
  await auth.login({ email: 'student@example.test', password: 'Disposable test password!' })
})
afterEach(() => vi.unstubAllGlobals())
const item = (n: number, percentage: number) => ({ attemptId: n.toString(16).padStart(24, '0'), quizId: '507f1f77bcf86cd799439011', quizTitle: 'SE quiz', subject: 'SE', score: percentage === 100 ? 1 : 0, percentage, answersSubmitted: 1, submittedAt: '2026-10-30T00:00:00.000Z' })
it('includes the 51st attempt in subject averages rather than truncating performance to the newest page', async () => {
  fetchMock.mockResolvedValueOnce(reply({ attempts: Array.from({ length: 50 }, (_, n) => item(n + 1, 100)), page: 1, pageSize: 50, total: 51, totalPages: 2 }))
  fetchMock.mockResolvedValueOnce(reply({ attempts: [item(51, 0)], page: 2, pageSize: 50, total: 51, totalPages: 2 }))
  const all = await history.getAllAttemptHistory()
  const { calculateAttemptInsights } = await import('./attemptInsights')
  const insights = calculateAttemptInsights(all.attempts)
  expect(all.attempts).toHaveLength(51)
  expect(insights.subjects[0]?.attempts).toBe(51)
  expect(insights.subjects[0]?.averagePercentage).toBe(98)
  expect(fetchMock.mock.calls[2]?.[0]).toContain('page=2')
})
it('rejects an incomplete or shifting history instead of presenting an incorrect subject average', async () => {
  fetchMock.mockResolvedValueOnce(reply({ attempts: [item(1, 100)], page: 1, pageSize: 50, total: 2, totalPages: 2 }))
  fetchMock.mockResolvedValueOnce(reply({ attempts: [item(1, 100)], page: 2, pageSize: 50, total: 2, totalPages: 2 }))
  await expect(history.getAllAttemptHistory()).rejects.toThrow('complete history')
})
it.each(['history', 'submission'])('clears expired shared authentication for %s', async kind => {
  fetchMock.mockResolvedValueOnce(reply({ error: { message: 'Expired' } }, 401))
  const pending = kind === 'history' ? history.getAttemptHistory() : attempts.submitQuizAttempt({ quizId: '507f1f77bcf86cd799439011', responses: [] })
  await expect(pending).rejects.toThrow('session has expired')
  expect(auth.getSessionToken()).toBeNull()
})
